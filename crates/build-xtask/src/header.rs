//! `cargo xtask header [--check]`: generates `runvil_plugin.h` from
//! `runvil-plugin-sys` with cbindgen, then writes it, or compares it with
//! the committed file and fails when they differ.

use std::fs;
use std::path::Path;
use std::process::ExitCode;

/// The crate the header mirrors, relative to the workspace root.
const SOURCE: &str = "crates/runvil-plugin-sys/src/lib.rs";
/// cbindgen's settings, relative to the workspace root.
const CONFIG: &str = "crates/runvil-plugin-sys/cbindgen.toml";
/// The generated header, relative to the workspace root.
const HEADER: &str = "crates/runvil-plugin-sys/include/runvil_plugin.h";

/// Writes the header, or with `--check` compares it with the committed one.
pub(crate) fn run(root: &Path, args: &[String]) -> ExitCode {
    let check = match args {
        [] => false,
        [flag] if flag == "--check" => true,
        _ => {
            eprintln!("usage: cargo xtask header [--check]");
            return ExitCode::from(2);
        }
    };
    let generated = match generate(root) {
        Ok(text) => text,
        Err(error) => {
            eprintln!("error: {error}");
            return ExitCode::FAILURE;
        }
    };
    let path = root.join(HEADER);
    if check {
        return match fs::read_to_string(&path) {
            Ok(committed) if is_current(&generated, &committed) => {
                println!("{HEADER} is current");
                ExitCode::SUCCESS
            }
            Ok(_) => {
                eprintln!("error: {HEADER} is stale: run `cargo xtask header`");
                ExitCode::FAILURE
            }
            Err(error) => {
                eprintln!("error: cannot read {HEADER}: {error}");
                ExitCode::FAILURE
            }
        };
    }
    let written = path
        .parent()
        .map_or(Ok(()), fs::create_dir_all)
        .and_then(|()| fs::write(&path, generated));
    match written {
        Ok(()) => {
            println!("wrote {HEADER}");
            ExitCode::SUCCESS
        }
        Err(error) => {
            eprintln!("error: cannot write {HEADER}: {error}");
            ExitCode::FAILURE
        }
    }
}

/// The header cbindgen writes for [`SOURCE`] with the settings in
/// [`CONFIG`]: opening with the crate docs as a C comment, declaring every
/// struct ahead of the definitions, and defining every struct, with
/// rustdoc's link brackets taken out of the comments.
///
/// # Errors
/// Returns a message naming what could not be read, parsed, or generated.
fn generate(root: &Path) -> Result<String, String> {
    let source_path = root.join(SOURCE);
    let source = fs::read_to_string(&source_path)
        .map_err(|error| format!("cannot read {SOURCE}: {error}"))?;
    let structs = struct_names(&source);
    let mut config = cbindgen::Config::from_file(root.join(CONFIG))
        .map_err(|error| format!("cannot read {CONFIG}: {error}"))?;
    let guard = config.header.take().unwrap_or_default();
    config.header = Some(format!("{}\n{guard}", opening_comment(&source)?));
    config.after_includes = Some(format!("\n{}", forward_typedefs(&structs)));
    config
        .export
        .include
        .extend(structs.iter().map(|name| (*name).to_owned()));
    let bindings = cbindgen::Builder::new()
        .with_config(config)
        .with_src(&source_path)
        .generate()
        .map_err(|error| format!("cbindgen failed on {SOURCE}: {error}"))?;
    let mut out = Vec::new();
    bindings.write(&mut out);
    let text = String::from_utf8(out)
        .map_err(|error| format!("cbindgen wrote a header that is not UTF-8: {error}"))?;
    Ok(plain_links(&text))
}

/// Whether `committed` is `generated`, ignoring a checkout that turned
/// its line endings into CRLF.
fn is_current(generated: &str, committed: &str) -> bool {
    committed.replace("\r\n", "\n") == generated
}

/// The header's opening C comment: what the file is, that it is
/// generated, and the crate docs, the leading `//!` lines of `source`, up
/// to their `## Invariants` section, which is about the Rust crate.
///
/// # Errors
/// Returns a message when a doc line holds `*/`, which would end the
/// comment early.
fn opening_comment(source: &str) -> Result<String, String> {
    let mut comment = String::from(
        "/* runvil_plugin.h\n *\n * Generated by `cargo xtask header` from \
         crates/runvil-plugin-sys/src/lib.rs.\n * Edit that file and \
         regenerate; never edit this one.\n *\n",
    );
    for line in source.lines() {
        let Some(doc) = line.strip_prefix("//!") else {
            break;
        };
        let text = doc.strip_prefix(' ').unwrap_or(doc);
        if text == "## Invariants" {
            break;
        }
        if text.contains("*/") {
            return Err(format!(
                "a crate doc line in {SOURCE} contains `*/`, which would end the header's comment: {text}"
            ));
        }
        if text.is_empty() {
            comment.push_str(" *\n");
        } else {
            comment.push_str(" * ");
            comment.push_str(text);
            comment.push('\n');
        }
    }
    while let Some(trimmed) = comment.strip_suffix(" *\n") {
        comment.truncate(trimmed.len());
    }
    comment.push_str(" */\n");
    Ok(comment)
}

/// The name of each top-level `pub struct` in `source`, in source order.
fn struct_names(source: &str) -> Vec<&str> {
    source
        .lines()
        .filter_map(|line| line.strip_prefix("pub struct "))
        .filter_map(|rest| rest.split([' ', '{', '<', '(', ';']).next())
        .collect()
}

/// One `typedef struct X X;` for each of `names`. Declaring every struct
/// ahead of the definitions lets each one name any other, as `RvDirEntry`
/// names `RvStat`, and lets C code write the name without `struct`.
fn forward_typedefs(names: &[&str]) -> String {
    names
        .iter()
        .map(|name| format!("typedef struct {name} {name};"))
        .collect::<Vec<_>>()
        .join("\n")
}

/// `text` with rustdoc's intra-doc link brackets taken out, so
/// ``[`RvHost`]`` in a doc comment reads `` `RvHost` `` in C.
fn plain_links(text: &str) -> String {
    text.replace("[`", "`").replace("`]", "`")
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::Path;

    use super::{
        HEADER, forward_typedefs, generate, is_current, opening_comment, plain_links, struct_names,
    };

    #[test]
    fn the_committed_header_matches_its_rust_source() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .ancestors()
            .nth(2)
            .unwrap();
        let generated = generate(root).unwrap();
        let committed = fs::read_to_string(root.join(HEADER)).unwrap();
        assert!(
            is_current(&generated, &committed),
            "{HEADER} is stale: run `cargo xtask header`"
        );
    }

    #[test]
    fn every_top_level_struct_is_found_and_gets_a_forward_typedef() {
        let source = "pub struct A {\n    pub struct Nested {\npub struct B<T>(T);\n";
        let names = struct_names(source);
        assert_eq!(names, ["A", "B"]);
        assert_eq!(
            forward_typedefs(&names),
            "typedef struct A A;\ntypedef struct B B;"
        );
    }

    #[test]
    fn the_opening_comment_carries_the_crate_docs_up_to_the_first_code_line() {
        let comment =
            opening_comment("//! First.\n//!\n//! Second.\nuse x;\n//! Not docs.\n").unwrap();
        assert!(
            comment.ends_with(" * First.\n *\n * Second.\n */\n"),
            "{comment}"
        );
        assert!(!comment.contains("Not docs."));
    }

    #[test]
    fn the_opening_comment_stops_before_the_invariants() {
        let comment =
            opening_comment("//! Contract.\n//!\n//! ## Invariants\n//!\n//! - Rust only.\n")
                .unwrap();
        assert!(comment.ends_with(" * Contract.\n */\n"), "{comment}");
        assert!(!comment.contains("Rust only."));
    }

    #[test]
    fn link_brackets_come_out_and_code_spans_stay() {
        assert_eq!(
            plain_links("see [`RvHost`] and `size`"),
            "see `RvHost` and `size`"
        );
    }

    #[test]
    fn a_doc_line_that_would_end_the_comment_is_refused() {
        let error = opening_comment("//! a */ b\n").unwrap_err();
        assert!(error.contains("`*/`"), "{error}");
    }

    #[test]
    fn a_crlf_checkout_is_still_current() {
        assert!(is_current("a\nb\n", "a\r\nb\r\n"));
        assert!(!is_current("a\nb\n", "a\nc\n"));
    }
}
